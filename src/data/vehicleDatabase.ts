export function findVehicleByKeywords(query: string): NormalizedVehicle | null {
  const q = query.toLowerCase().trim();
  return (
    APEX_LOCAL_VEHICLE_DATABASE.find(v => {
      const full = `${v.manufacturer} ${v.model} ${v.generation || ''} ${v.trim || ''}`.toLowerCase();
      return full.includes(q) || q.includes(v.model.toLowerCase());
    }) || null
  );
}
